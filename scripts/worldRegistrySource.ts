/** Static imports keep the domain browser-free and identical in Node/Vite. */
export function worldRegistrySource(
  sceneFiles: readonly string[],
  artFiles: readonly string[],
): { scenes: string; art: string } {
  const names = (files: readonly string[], suffix: string) => {
    if (
      new Set(files).size !== files.length ||
      files.some(
        (f) => !new RegExp(`^[a-z][a-z0-9-]*\\.${suffix}\\.ts$`).test(f),
      )
    )
      throw new Error('invalid or duplicate world module filename');
    return [...files].sort();
  };
  const scenes = names(sceneFiles, 'scenes'),
    art = names(artFiles, 'art');
  const header =
    '// Generated by scripts/generate-world-registries.ts; do not edit.\n';
  return {
    scenes:
      header +
      "import type { LocalityTemplate } from '../sceneryTypes.ts';\n" +
      scenes
        .map((f, i) => `import { scenes as scene${i} } from './${f}';\n`)
        .join('') +
      `export const additionalScenes: readonly LocalityTemplate[] = [${scenes.map((_, i) => `...scene${i}`).join(',')}];\n`,
    art:
      header +
      "import type { ArtPart } from './artManifest.ts';\n" +
      art
        .map((f, i) => `import * as art${i} from './world-modules/${f}';\n`)
        .join('') +
      `export const additionalWorldParts = {${art.map((_, i) => `...art${i}.parts`).join(',')}} as const satisfies Record<string, ArtPart>;\n` +
      `export const additionalWorldUsedKeys: readonly string[] = [${art.map((_, i) => `...art${i}.usedKeys`).join(',')}];\n` +
      `export const additionalPartKeys: readonly string[] = [${art.map((_, i) => `...Object.keys(art${i}.parts)`).join(',')}];\n`,
  };
}
